-- Wird fuer den Constraint gegen ueberlappende Abwesenheiten gebraucht
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TYPE absence_status AS ENUM ('OPEN', 'APPROVED', 'REJECTED');

-- Benutzer: id ist die User-ID aus Keycloak (wird beim ersten Login uebernommen)
CREATE TABLE app_user (
    id         uuid         PRIMARY KEY,
    first_name varchar(255) NOT NULL,
    last_name  varchar(255) NOT NULL,
    email      varchar(255) NOT NULL UNIQUE
);

-- Abwesenheiten
CREATE TABLE absence (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      uuid           NOT NULL REFERENCES app_user (id),
    created_from uuid           NOT NULL REFERENCES app_user (id),
    updated_from uuid           REFERENCES app_user (id),
    start_date   date           NOT NULL,
    end_date     date           NOT NULL,
    title        varchar(255),
    status       absence_status NOT NULL,
    version      smallint       NOT NULL DEFAULT 0,
    created_at   timestamptz    NOT NULL DEFAULT now(),
    updated_at   timestamptz,

    -- Das Ende liegt nicht vor dem Beginn
    CONSTRAINT absence_dates_check CHECK (end_date >= start_date),

    -- updated_from und updated_at sind nur gemeinsam gefuellt oder gemeinsam leer
    CONSTRAINT absence_updated_check CHECK ((updated_from IS NULL) = (updated_at IS NULL)),

    -- Abwesenheiten derselben Person ueberschneiden sich nicht (abgelehnte Eintraege ausgenommen)
    CONSTRAINT absence_no_overlap EXCLUDE USING gist (
        user_id WITH =,
        daterange(start_date, end_date, '[]') WITH &&
    ) WHERE (status <> 'REJECTED')
);

-- Fuer die Kalenderansicht (alle Abwesenheiten in einem Zeitraum)
CREATE INDEX absence_dates_idx ON absence (start_date, end_date);

-- Urlaubsanspruch pro Benutzer und Jahr
CREATE TABLE vacation_entitlement (
    user_id uuid     NOT NULL REFERENCES app_user (id),
    year    smallint NOT NULL,
    days    smallint NOT NULL,
    PRIMARY KEY (user_id, year),
    CONSTRAINT vacation_entitlement_days_check CHECK (days >= 0)
);

-- Gesetzliche Feiertage (Zwischenspeicher der Feiertags-API)
CREATE TABLE public_holiday (
    holiday_date date         PRIMARY KEY,
    name         varchar(255) NOT NULL
);
