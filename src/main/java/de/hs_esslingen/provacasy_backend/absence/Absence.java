package de.hs_esslingen.provacasy_backend.absence;

import java.time.Instant;
import java.time.LocalDate;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.Version;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import de.hs_esslingen.provacasy_backend.user.User;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Eine Abwesenheit im Kalender (Tabelle absence aus V1__init.sql).
 */
// @Entity: Hibernate verwaltet diese Klasse, ein Objekt entspricht einer Zeile in der Tabelle.
// @Table: Name der Tabelle. Ohne die Angabe würde Hibernate den Klassennamen nehmen.
// Das Schema selbst legt nur Flyway an. Hibernate prüft beim Start nur, ob Klasse und Tabelle
// zusammenpassen (ddl-auto=validate), und bricht sonst ab.
@Entity
@Table(name = "absence")
// Lombok erzeugt beim Kompilieren für jedes Feld einen Getter (getStartDate() usw.).
@Getter
// Hibernate braucht einen Konstruktor ohne Parameter, um Objekte aus der Datenbank zu bauen.
// PROTECTED, damit im eigenen Code niemand eine "leere" Abwesenheit ohne Pflichtfelder anlegt.
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class Absence {

    // @Id: Primärschlüssel. IDENTITY heißt: Die Datenbank vergibt die Nummer selbst
    // (Spalte "generated by default as identity"). Vor dem ersten Speichern ist id deshalb null.
    // updatable = false: Hibernate schreibt die Spalte bei einem UPDATE nie mit.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false, updatable = false)
    private Long id;

    // @Setter nur an Feldern, die sich fachlich ändern dürfen (PUT /api/absences/{id}).
    // id, user, createdFrom, version und createdAt haben bewusst keinen Setter.
    @Setter
    @Column(name = "start_date", nullable = false)
    private LocalDate startDate;

    @Setter
    @Column(name = "end_date", nullable = false)
    private LocalDate endDate;

    // Ohne nullable = false: Die Bezeichnung ist optional.
    @Setter
    @Column(name = "title")
    private String title;

    // @ManyToOne: Viele Abwesenheiten gehören zu einem User. In der Tabelle steht nur die UUID
    // (Fremdschlüssel user_id), in Java bekommt man das ganze User Objekt.
    // LAZY: Der User wird erst aus der Datenbank geladen, wenn man wirklich auf ihn zugreift
    // (z. B. getUser().getFirstName()). getUser().getId() reicht ohne extra Abfrage, weil die
    // ID schon in der Spalte user_id steht.
    // @JoinColumn: Name der Fremdschlüsselspalte in der Tabelle absence.
    /** Wer abwesend ist (Beziehung "betrifft"). Kann nach dem Anlegen nicht geändert werden. */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false, updatable = false)
    private User user;

    /** Wer den Eintrag angelegt hat (Beziehung "erfasst von"): die Person selbst, das Sekretariat oder das Dekanat. */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "created_from", nullable = false, updatable = false)
    private User createdFrom;

    // Ohne optional = false: Die Spalte darf null sein.
    /** Wer den Eintrag zuletzt geändert hat (Beziehung "geändert von"). Leer, solange er unverändert ist. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "updated_from")
    private User updatedFrom;

    // @Enumerated(STRING): Gespeichert wird der Name ("OPEN"), nicht die Position (0, 1, 2).
    // Würde jemand die Reihenfolge im Enum ändern, wären mit Positionen alle Daten falsch.
    // @JdbcTypeCode(NAMED_ENUM): Die Spalte ist in PostgreSQL kein Text, sondern der eigene Typ
    // absence_status. Ohne diese Angabe schickt Hibernate Text und PostgreSQL lehnt ab.
    /** Offen, genehmigt oder abgelehnt. In der Datenbank der eigene Typ absence_status. */
    @Setter
    @Enumerated(EnumType.STRING)
    @JdbcTypeCode(SqlTypes.NAMED_ENUM)
    @Column(name = "status", nullable = false)
    private AbsenceStatus status;

    // @Version: Hibernate zählt das Feld bei jedem UPDATE selbst hoch und prüft dabei mit
    // "WHERE version = <alter Wert>", ob jemand anderes den Eintrag inzwischen geändert hat.
    // Wenn ja, wird nichts gespeichert und es gibt eine Exception (später 409 Conflict).
    /** Steigt bei jeder Änderung um 1 (optimistisches Sperren) und ist die SEQUENCE der ICS Datei. */
    @Version
    @Column(name = "version", nullable = false)
    private Short version;

    // @CreationTimestamp: Hibernate setzt die aktuelle Zeit beim ersten Speichern (INSERT).
    // Instant ist ein Zeitpunkt ohne Zeitzone, passend zur Spalte timestamptz.
    /** Zeitpunkt des Anlegens, wird beim ersten Speichern automatisch gesetzt. */
    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    // Absichtlich kein @UpdateTimestamp: Der würde updated_at bei jedem UPDATE setzen, auch wenn
    // updated_from leer bleibt. Das verbietet der Constraint absence_updated_check.
    // Deshalb setzt markUpdated() beide Felder gemeinsam.
    /** Zeitpunkt der letzten Änderung, wird nur zusammen mit updatedFrom gesetzt. */
    @Column(name = "updated_at")
    private Instant updatedAt;

    /**
     * Legt eine neue Abwesenheit an.
     * Den Status bestimmt der Service: OPEN, wenn ein Professor für sich selbst einträgt,
     * APPROVED, wenn Sekretariat oder Dekanat für eine andere Person eintragen.
     */
    // id, version und createdAt fehlen hier absichtlich: Die setzen Datenbank und Hibernate.
    public Absence(User user, User createdFrom, LocalDate startDate, LocalDate endDate,
                   String title, AbsenceStatus status) {
        this.user = user;
        this.createdFrom = createdFrom;
        this.startDate = startDate;
        this.endDate = endDate;
        this.title = title;
        this.status = status;
    }

    /**
     * Merkt sich, wer den Eintrag wann zuletzt geändert hat.
     * updated_from und updated_at werden immer zusammen gesetzt (Constraint absence_updated_check).
     */
    public void markUpdated(User updatedFrom) {
        this.updatedFrom = updatedFrom;
        this.updatedAt = Instant.now();
    }
}
